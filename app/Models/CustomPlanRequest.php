<?php

namespace App\Models;

use App\Enums\CustomPlanRequestStatus;
use Database\Factories\CustomPlanRequestFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

#[Fillable([
    'organization_id',
    'requested_by',
    'requested_max_stores',
    'requested_max_owners',
    'message',
    'status',
    'reviewed_by',
    'reviewed_at',
])]
class CustomPlanRequest extends Model
{
    /** @use HasFactory<CustomPlanRequestFactory> */
    use HasFactory;

    /**
     * @return BelongsTo<Organization, $this>
     */
    public function organization(): BelongsTo
    {
        return $this->belongsTo(Organization::class);
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function requestedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'requested_by');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function reviewedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'reviewed_by');
    }

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'status' => CustomPlanRequestStatus::class,
            'reviewed_at' => 'datetime',
        ];
    }
}
